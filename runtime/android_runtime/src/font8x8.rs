// Self-contained ASCII font table (characters 32..126) + custom symbols:
//   - Bullet (• / ●)
//   - Upward triangle (▲)
//   - Solid diamond (◆)
//   - Outlined diamond (◈)
//   - Solid square (■)
//   - Checkmark (✓)
// Generates a 128x64 32-bit RGBA texture uploaded to OpenGL ES 2.0.
// =============================================================================

pub const FONT_WIDTH: usize = 8;
pub const FONT_HEIGHT: usize = 8;
pub const FIRST_CHAR: u8 = 32;
pub const NUM_CHARS: usize = 102; // 96 standard ASCII + 6 custom symbols

// 16 columns x 8 rows = 128 glyphs (128x64 texture)
pub const ATLAS_WIDTH: usize = 128;
pub const ATLAS_HEIGHT: usize = 64;

/// Generates a 128x64 32-bit RGBA bitmap containing all glyphs with subpixel antialiasing.
pub fn generate_font_atlas_rgba() -> Vec<u8> {
    let mut atlas = vec![0u8; ATLAS_WIDTH * ATLAS_HEIGHT * 4];

    for ch_idx in 0..NUM_CHARS {
        let glyph_bytes = get_glyph_by_idx(ch_idx);

        let grid_x = (ch_idx % 16) * FONT_WIDTH;
        let grid_y = (ch_idx / 16) * FONT_HEIGHT;

        // Extract 8x8 binary grid
        let mut grid = [[0u8; 8]; 8];
        for row in 0..8 {
            let byte = glyph_bytes[row];
            for col in 0..8 {
                grid[row][col] = (byte >> (7 - col)) & 1;
            }
        }

        // Apply 3x3 Gaussian smoothing kernel for subpixel vector antialiasing
        for row in 0..8 {
            for col in 0..8 {
                let mut weight = 0u32;
                let mut sum = 0u32;

                for dy in -1i32..=1i32 {
                    for dx in -1i32..=1i32 {
                        let ny = row as i32 + dy;
                        let nx = col as i32 + dx;
                        let w = match (dy.abs(), dx.abs()) {
                            (0, 0) => 8,
                            (0, 1) | (1, 0) => 3,
                            _ => 1,
                        };
                        weight += w;
                        if ny >= 0 && ny < 8 && nx >= 0 && nx < 8 {
                            if grid[ny as usize][nx as usize] == 1 {
                                sum += w * 255;
                            }
                        }
                    }
                }

                let alpha = (sum / weight) as u8;
                let pixel_idx = ((grid_y + row) * ATLAS_WIDTH + (grid_x + col)) * 4;
                if pixel_idx + 3 < atlas.len() {
                    atlas[pixel_idx]     = alpha;
                    atlas[pixel_idx + 1] = alpha;
                    atlas[pixel_idx + 2] = alpha;
                    atlas[pixel_idx + 3] = alpha;
                }
            }
        }
    }

    atlas
}

/// Returns texture coordinates (u0, v0, u1, v1) for an ASCII or custom symbol character.
pub fn get_char_uv(ch: char) -> (f32, f32, f32, f32) {
    let idx = match ch {
        '•' | '●' => 96,
        '▲'       => 97,
        '◆'       => 98,
        '◈'       => 99,
        '■'       => 100,
        '✓'       => 101,
        _ => {
            let c = ch as usize;
            if c >= 32 && c < 128 {
                c - 32
            } else {
                '?' as usize - 32
            }
        }
    };

    let grid_x = (idx % 16) * FONT_WIDTH;
    let grid_y = (idx / 16) * FONT_HEIGHT;

    let u0 = grid_x as f32 / ATLAS_WIDTH as f32;
    let v0 = grid_y as f32 / ATLAS_HEIGHT as f32;
    let u1 = (grid_x + FONT_WIDTH) as f32 / ATLAS_WIDTH as f32;
    let v1 = (grid_y + FONT_HEIGHT) as f32 / ATLAS_HEIGHT as f32;

    (u0, v0, u1, v1)
}

fn get_glyph_by_idx(idx: usize) -> [u8; 8] {
    if idx < 96 {
        get_glyph((FIRST_CHAR as usize + idx) as u8)
    } else {
        match idx {
            96  => [0x00, 0x18, 0x3C, 0x3C, 0x3C, 0x3C, 0x18, 0x00], // • / ●
            97  => [0x00, 0x18, 0x3C, 0x3C, 0x7E, 0x7E, 0xFF, 0x00], // ▲
            98  => [0x00, 0x18, 0x3C, 0x7E, 0x7E, 0x3C, 0x18, 0x00], // ◆
            99  => [0x00, 0x18, 0x24, 0x42, 0x42, 0x24, 0x18, 0x00], // ◈
            100 => [0x00, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x7E, 0x00], // ■
            101 => [0x00, 0x02, 0x06, 0x8C, 0xD8, 0x70, 0x20, 0x00], // ✓
            _   => [0x7E, 0x42, 0x5A, 0x5A, 0x42, 0x7E, 0x00, 0x00],
        }
    }
}

